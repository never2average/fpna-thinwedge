                    "workingDirectory": model_repo_root,
                },
            },
            "metadata": {"family": "xgboost"},
        }
    ]
}
print(json.dumps(payload))
PY

THINWEDGE_FIXTURE_ENV_REPO_ROOT="$environment_repo_root" \
THINWEDGE_FIXTURE_SCRIPT_ROOT="$script_root" \
THINWEDGE_FIXTURE_RUNPOD_TEMPLATE_ID="$runpod_template_id" \
THINWEDGE_FIXTURE_RUNPOD_GPU_TYPE_ID="$runpod_gpu_type_id" \
THINWEDGE_FIXTURE_RUNPOD_NETWORK_VOLUME_ID="$runpod_network_volume_id" \
THINWEDGE_FIXTURE_RUNPOD_CLOUD_TYPE="$runpod_cloud_type" \
THINWEDGE_FIXTURE_RUNPOD_SUPPORT_PUBLIC_IP="$runpod_support_public_ip" \
THINWEDGE_FIXTURE_RUNPOD_SSH_PUBLIC_KEY="$runpod_ssh_public_key" \
THINWEDGE_FIXTURE_RUNPOD_SSH_PRIVATE_KEY_PATH="$runpod_ssh_private_key_path" \
THINWEDGE_FIXTURE_RUNPOD_IMAGE_NAME="$runpod_image_name" \
THINWEDGE_FIXTURE_RUNPOD_DOCKER_ENTRYPOINT_JSON="$runpod_docker_entrypoint_json" \
THINWEDGE_FIXTURE_RUNPOD_DOCKER_START_CMD_JSON="$runpod_docker_start_cmd_json" \
THINWEDGE_FIXTURE_RUNPOD_GLOBAL_NETWORKING="$runpod_global_networking" \
THINWEDGE_FIXTURE_RUNPOD_CONTROL_TOKEN="$runpod_control_token" \
THINWEDGE_FIXTURE_RUNPOD_CONTROL_PORT="$runpod_control_port" \
THINWEDGE_FIXTURE_RUNPOD_CONTROL_SERVER_B64="$control_server_b64" \
THINWEDGE_FIXTURE_RUNTIME_FAMILY="$runtime_family" \
python3 - <<'PY' | thinwedge_write_json_file "$environments_path"
