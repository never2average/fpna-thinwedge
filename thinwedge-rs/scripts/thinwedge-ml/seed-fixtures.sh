import os

script_root = os.environ["THINWEDGE_FIXTURE_SCRIPT_ROOT"]
model_repo_root = os.environ["THINWEDGE_FIXTURE_MODEL_REPO_ROOT"]
payload = {
    "models": [
        {
            "id": "model-pricing",
            "name": "Pricing Model",
            "description": "ThinWedge sample pricing model",
            "tags": ["pricing", "gpu"],
            "visibleToRoles": ["pricing_researcher"],
            "defaultEnvironmentId": "env-pricing",
            "repository": {
                "root": model_repo_root,
                "configPath": f"{model_repo_root}/config.yaml",
                "refName": "main",
                "entrypoint": "scripts/train.sh",
                "batchEntryPoint": "scripts/run_batch_inference.py",
            },
            "tools": {
                "submitTraining": {
                    "command": f"bash {script_root}/train.sh",
