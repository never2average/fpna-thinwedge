import os

script_root = os.environ["THINWEDGE_FIXTURE_SCRIPT_ROOT"]
environment_repo_root = os.environ["THINWEDGE_FIXTURE_ENV_REPO_ROOT"]
network_volume_id = os.environ.get("THINWEDGE_FIXTURE_RUNPOD_NETWORK_VOLUME_ID") or None
ssh_public_key = os.environ.get("THINWEDGE_FIXTURE_RUNPOD_SSH_PUBLIC_KEY") or None
ssh_private_key_path = os.environ.get("THINWEDGE_FIXTURE_RUNPOD_SSH_PRIVATE_KEY_PATH") or None
image_name = os.environ.get("THINWEDGE_FIXTURE_RUNPOD_IMAGE_NAME") or None
docker_entrypoint_json = os.environ.get("THINWEDGE_FIXTURE_RUNPOD_DOCKER_ENTRYPOINT_JSON") or ""
docker_start_cmd_json = os.environ.get("THINWEDGE_FIXTURE_RUNPOD_DOCKER_START_CMD_JSON") or ""
runpod = {
    "templateId": os.environ["THINWEDGE_FIXTURE_RUNPOD_TEMPLATE_ID"],
    "gpuCount": 1,
    "gpuTypeId": os.environ["THINWEDGE_FIXTURE_RUNPOD_GPU_TYPE_ID"],
    "volumeMountPath": "/workspace",
    "workspacePath": "/workspace/thinwedge/env-pricing",
    "exposedHttpPort": int(os.environ["THINWEDGE_FIXTURE_RUNPOD_CONTROL_PORT"]),
    "supportsSsh": True,
    "name": "thinwedge-pricing-env",
    "cloudType": os.environ["THINWEDGE_FIXTURE_RUNPOD_CLOUD_TYPE"],
    "globalNetworking": os.environ["THINWEDGE_FIXTURE_RUNPOD_GLOBAL_NETWORKING"].lower() == "true",
    "containerDiskInGb": 50,
    "volumeInGb": 100,
    "supportPublicIp": os.environ["THINWEDGE_FIXTURE_RUNPOD_SUPPORT_PUBLIC_IP"].lower() == "true",
    "stopMode": "stop",
    "startupTimeoutSec": 900,
    "env": {
        "THINWEDGE_MODEL_REPOSITORY_ROOT": "/workspace/thinwedge/model-pricing-repo",
        "THINWEDGE_ENV_REPOSITORY_ROOT": "/workspace/thinwedge/env-pricing-repo",
        "THINWEDGE_RUNTIME_FAMILY": os.environ["THINWEDGE_FIXTURE_RUNTIME_FAMILY"],
        "THINWEDGE_CONTROL_TOKEN": os.environ["THINWEDGE_FIXTURE_RUNPOD_CONTROL_TOKEN"],
        "THINWEDGE_CONTROL_PORT": os.environ["THINWEDGE_FIXTURE_RUNPOD_CONTROL_PORT"],
        "THINWEDGE_CONTROL_SERVER_B64": os.environ["THINWEDGE_FIXTURE_RUNPOD_CONTROL_SERVER_B64"],
    }
}
if network_volume_id:
    runpod["networkVolumeId"] = network_volume_id
if ssh_public_key:
    runpod["env"]["SSH_PUBLIC_KEY"] = ssh_public_key
    runpod["env"]["PUBLIC_KEY"] = ssh_public_key
if ssh_private_key_path:
    runpod["sshPrivateKeyPath"] = ssh_private_key_path
if image_name:
    runpod["imageName"] = image_name
if docker_entrypoint_json:
    runpod["dockerEntrypoint"] = json.loads(docker_entrypoint_json)
if docker_start_cmd_json:
    runpod["dockerStartCmd"] = json.loads(docker_start_cmd_json)
payload = {
    "environments": [
        {
            "id": "env-pricing",
            "name": "Pricing GPU",
